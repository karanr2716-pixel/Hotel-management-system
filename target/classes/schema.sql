CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type VARCHAR(31) NOT NULL,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS hotels (
    hotel_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    city VARCHAR(120) NOT NULL,
    description VARCHAR(1200) NOT NULL,
    image_url VARCHAR(600) NOT NULL,
    rating DECIMAL(2, 1) NOT NULL
);

CREATE TABLE IF NOT EXISTS rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type VARCHAR(31) NOT NULL,
    room_number VARCHAR(80) NOT NULL UNIQUE,
    hotel_id BIGINT NOT NULL,
    price_per_night DECIMAL(10, 2) NOT NULL,
    max_guests INTEGER NOT NULL DEFAULT 2,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_rooms_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (hotel_id)
);

CREATE TABLE IF NOT EXISTS room_amenities (
    room_id BIGINT NOT NULL,
    amenity VARCHAR(255) NOT NULL,
    CONSTRAINT fk_amenities_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT pk_room_amenities PRIMARY KEY (room_id, amenity)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    status VARCHAR(32) NOT NULL,
    nightly_rate DECIMAL(10, 2) NOT NULL,
    total_amount DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT ck_booking_dates CHECK (check_out > check_in)
);
